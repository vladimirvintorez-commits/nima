def time_sense(now=None) -> str:
    """Блок «ритм дня» для промпта по текущему часу (ночь = сонная, вечер = своя)."""
    import datetime as _dt
    now = now or _dt.datetime.now()
    h = now.hour
    if 0 <= h < 3:
        key = "поздняя ночь"
    elif 3 <= h < 6:
        key = "ночь"
    elif 6 <= h < 11:
        key = "утро"
    elif 11 <= h < 18:
        key = "день"
    else:
        key = "вечер"
    return _TIME_BLOCKS[key]
