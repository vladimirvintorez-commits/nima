    rows: list[dict] = []
    seen: set[tuple[str, str]] = set()

    def add(user: str, assistant: str, weight: int = 1) -> None:
        key = (user.strip().lower(), assistant.strip().lower())
        if key in seen or not user.strip() or not assistant.strip():
            return
        seen.add(key)
        text = assistant.strip()
        if text[:1].islower():          # реплика начинается с заглавной
            text = text[0].upper() + text[1:]
        for _ in range(weight):
            rows.append({"messages": [
                {"role": "system", "content": SYSTEM_SHORT},
                {"role": "user", "content": user.strip()},
                {"role": "assistant", "content": text},
            ]})

    for pair in manual:
        add(pair[0], pair[1], weight=MANUAL_WEIGHT)
    for user, assistant in scenes:
        add(user, assistant)

    # добор повторами сцен с иным контекстом не делаем — качество важнее объёма;
    # если сидов не хватило — предупредим, но всё равно отдалим до TARGET повторами
    # уникальных сцен (для LoRA безопасно при малом lr, но лучше дописать руки).
    if len(seen) < TARGET:
        unique = list(seen)
        rng.shuffle(unique)
        for user, assistant in unique[: TARGET - len(seen)]:
            rows.append({"messages": [
                {"role": "system", "content": SYSTEM_SHORT},
                {"role": "user", "content": user},
                {"role": "assistant", "content": assistant},
            ]})

    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        for i, row in enumerate(rows):
            row_out = {"id": i, **row}
            fh.write(json.dumps(row_out, ensure_ascii=False) + "\n")

    PROMPT_PATH.write_text(SYSTEM_SHORT, encoding="utf-8")

    print(f"готово: {len(rows)} примеров (уникальных пар: {len(seen)})")
    print(f"файл: {OUT_PATH}")
    print(f"system: {PROMPT_PATH}")


